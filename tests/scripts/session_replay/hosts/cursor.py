"""Parse a Cursor Agent CLI transcript `.jsonl` into a `session_model.Session`.

Verified against every `~/.cursor/projects/*/agent-transcripts/*/*.jsonl` on
this machine (627 files, 15,845 lines — read only, never copied into the
repo), with `7d8cbab1-0d90-4155-962b-7654f6f5bfcd` (Cursor 2026.08.31, the
first fully sctx-compliant Cursor session) as the S4 validation fixture.

## Transcript location and identity

`~/.cursor/projects/<cwd-slug>/agent-transcripts/<conversation_id>/<conversation_id>.jsonl`,
where `<cwd-slug>` is the session's startup directory with every run of
non-alphanumeric characters collapsed to `-` (so `_` and `/` both become
`-` and the slug is NOT reversible into a path — see `resolve_cwd`).

`<conversation_id>` is simultaneously the hook payload's `conversation_id`
/ `session_id`, the `external_session_id` the model passes to every sctx MCP
tool, and `external_session.external_session_key` with `agent_kind='cursor'`.
One id, no mapping table.

## Line shapes (exhaustive over all 627 files)

Exactly three top-level shapes exist:

  {"role": "user"|"assistant", "message": {"content": [block, ...]}}
  {"type": "turn_ended", "status": "success"}
  {"type": "turn_ended", "status": "error"|"aborted", "error": "<text>"}

and exactly three block shapes:

  {"type": "text", "text": ...}                      (user and assistant)
  {"type": "tool_use", "name": ..., "input": {...}}   (assistant only)

Note what is NOT there, because these absences drive everything below:

  - **No timestamps on any line.** The only clock in the file is the
    `<timestamp>` tag Cursor prepends inside the *user* message text.
  - **No tool_result blocks at all.** Every tool call's output — shell
    output, file contents, and every sctx MCP response — is absent from the
    transcript. (Large outputs are spilled to sibling
    `projects/<slug>/agent-tools/<uuid>.txt` files, but `tool_use` blocks
    carry no id, those files are shared across every conversation in the
    project, and only outputs above some size threshold land there, so they
    cannot be attributed back to a call. They are deliberately not read.)
  - **No hook injections.** Cursor never writes the `additionalContext` a
    hook returns into the transcript, so nothing sctx pushed is visible here.
  - **No tool_use ids, no usage/token records, no git metadata, no cwd, no
    model, no compaction markers.**

## Human prompts vs. the host talking

Every user message wraps the real prompt in `<user_query>...</user_query>`,
usually preceded by `<timestamp>...</timestamp>` and occasionally by a
`<manually_attached_skills>` or `<cursor_commands>` preamble that inlines
skill/command text ahead of the query (1002 timestamped + 70 untimestamped +
45 skill-preamble messages carry a `<user_query>`; 7 do not).

A user message is the HOST talking, not a human, when either:
  - it carries no `<user_query>` at all (observed: "Your previous response
    was interrupted. Continue from where you left off."), or
  - its query text opens with one of `HOST_QUERY_PREFIXES` — Cursor's own
    post-tool / post-subagent continuation prompts ("Briefly inform the user
    about the task result…", "The beginning of the above subagent result is
    already visible…"), which are generated by the client, not typed.

Host-talking user messages do NOT open a new `Turn` (their work folds into
the preceding human turn, exactly as `hosts/codex.py` folds the AGENTS.md
preamble); they are recorded in `Session.other_injections` so the digest
still shows they happened. This keeps `len(session.turns) == human prompts`,
the invariant `bundle.compute_facts` relies on.

## sctx MCP calls

Cursor exposes sctx through a dynamic-tool indirection rather than as native
tools: `tool_use name="GetDynamicTools" input={namespace, toolName|pattern}`
discovers a tool, then `tool_use name="CallDynamicTool"` invokes it with
`input = {namespace, toolName, arguments, mcpDetails?}`. An sctx call is one
whose `namespace` names the `shared-context` MCP server, with or without the
scope prefix Cursor adds -- both `user-shared-context` (110 calls in the real
transcripts here) and bare `shared-context` (47) occur, and which one you get
depends on how the server was registered, not on anything about the call. See
`is_sctx_namespace`. `arguments` is normally an object
but is sometimes a JSON *string* (observed once in the fixture) — both are
accepted and the string is parsed, since `SctxCall.arguments` must be the
full structured arguments for `facts.json`'s claim counting.

Because the transcript holds no results, every `SctxCall` from this host has
`status="unknown"` and `result_text=None`. `error_code` is always None: a
failed sctx call is indistinguishable from a successful one here.

## Injections: reconstructed from sctx, never from the transcript

`reconstruct_from_sctx()` rebuilds the injection timeline out of sctx's own
state, and flags every `Injection` it produces with
`reconstructed_from="sctx:task_injection"`:

  - `runtime.sqlite` `task_injection` rows for this session's task ids, each
    carrying `context_id`, `source` and `injected_at_unix_seconds`. Rows
    sharing a `(source, injected_at_unix_seconds)` pair are one injection
    event, so they are grouped into a single `Injection` whose `ctx_ids` is
    the group. `text` is a synthetic one-line summary and `wire_bytes` /
    `est_tokens` stay 0 — the injected TEXT is nowhere on disk, only the
    identity of what was injected.
  - `~/.shared-context-logs/state/hook-diagnostics.json` `recent_events`
    filtered by `sctx_logs.telemetry_session_digest("cursor", <id>)`. The
    digest formula is host-agnostic and gated on `{"cursor","codex"}` in the
    Rust source, and it matches for real Cursor sessions (verified: 328
    events for the fixture, `hook.cursor.session_start` through
    `hook.cursor.turn_stop`). These become per-turn `HookEvent` aggregates,
    not `Injection`s — they say a hook ran, not that context arrived.

Both are bucketed into turns by the `<timestamp>` clock: turn *n* owns
`[start_n, start_{n+1})`, with turn 1's lower bound open (so the
session_start hook, which fires seconds before the first prompt is stamped,
lands in turn 1) and the last turn's upper bound open. Cursor stamps
timestamps only to the minute, so a row within ~60s of a turn boundary can
land on either side; anything that cannot be bucketed at all (no timestamps
in the transcript, or the session has no turns) is reported under
`Session.reconstruction["unwindowed"]` instead of being guessed into a turn.
"""
