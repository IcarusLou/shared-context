# The `namespace` on a dynamic-tool call is the MCP SERVER name as Cursor
# resolved it, and Cursor prefixes it with the scope the server was registered
# in. Both spellings occur in real transcripts on this machine
# (`user-shared-context` 110×, `shared-context` 47×), and the S4 replay
# produced the unprefixed one from an isolated CURSOR_CONFIG_DIR while the
# original produced the prefixed one -- so matching the literal string would
# have found zero sctx calls in the replay of a session full of them. Match the
# server name with any scope prefix instead.
SCTX_SERVER_NAME = "shared-context"
DYNAMIC_CALL_TOOL = "CallDynamicTool"
DYNAMIC_DISCOVER_TOOL = "GetDynamicTools"


def is_sctx_namespace(namespace) -> bool:
    if not isinstance(namespace, str):
        return False
    return namespace == SCTX_SERVER_NAME or namespace.endswith(f"-{SCTX_SERVER_NAME}")

USER_QUERY_RE = re.compile(r"<user_query>(.*?)</user_query>", re.DOTALL)
TIMESTAMP_RE = re.compile(r"<timestamp>(.*?)</timestamp>", re.DOTALL)

# Cursor's own continuation prompts. They arrive as `role: "user"` messages
# with a normal `<user_query>` wrapper, but no human typed them: the client
# emits them after a queued tool run or a finished subagent. Replaying one
# would fabricate a prompt the original human never sent.
HOST_QUERY_PREFIXES = (
    "Briefly inform the user about the task result",
    "The beginning of the above subagent result is already visible",
    "Your previous response was interrupted",
)

FIDELITY_NOTES = (
    "tool outputs are NOT recorded by Cursor: every tool_use block in the "
    "transcript has no paired result, so sctx MCP responses (accept/reject, "
    "returned candidates, returned context packs) are unavailable — "
    "sctx_calls carry status=unknown and no result text",
    "hook injections are NOT recorded by Cursor: the transcript never shows "
    "what sctx pushed, so every injection below is RECONSTRUCTED from sctx's "
    "own runtime.sqlite/task_injection rows — the context ids and the time "
    "are real, the injected text is unrecoverable and wire_bytes/est_tokens "
    "are therefore 0, not measured",
    "no token usage, git commit, model or compaction markers are recorded by "
    "Cursor; those fields are empty rather than zero-valued findings",
)

# task_injection.source -> Injection.kind. Observed values across the real
# database: intent_update (170), task_context (7), artifact_focus (2). The
# host-agnostic kinds in session_model are Codex-hook-shaped, and none of
# these map onto them cleanly, so the sctx source name is kept verbatim and
# prefixed to stay obviously distinct from a transcript-read Codex kind.
def _injection_kind(source: Optional[str]) -> str:
    return f"sctx:{source}" if source else "sctx:unknown"


def slugify_cwd(path: str) -> str:
    """Reproduces Cursor's project-directory slug for a startup directory.

    Verified against the real project directories on this machine:
    `/Users/<user>/work/cross/fe/search_web_monorepo` ->
    `Users-<user>-work-cross-fe-search-web-monorepo`. The mapping is
    lossy (both `/` and `_` become `-`), which is why `resolve_cwd` searches
    candidate paths forward through this function instead of inverting it.
    """
    return re.sub(r"[^A-Za-z0-9]+", "-", path).strip("-")


def resolve_transcript(
    conversation_id: str, cursor_home: Optional[Path] = None
) -> Optional[Path]:
    """Resolve a Cursor conversation id to its transcript `.jsonl`.

    `cursor_home` defaults to `~/.cursor` (Cursor's own state; independent of
    the sctx `--home` flag). The conversation id is globally unique across
    projects, so the project slug does not need to be known in advance.
    """
    home = cursor_home or (Path.home() / ".cursor")
    projects = home / "projects"
    if not projects.is_dir():
        return None
    direct = sorted(
        projects.glob(f"*/agent-transcripts/{conversation_id}/{conversation_id}.jsonl")
    )
    if direct:
        return direct[0]
    loose = sorted(projects.glob(f"*/agent-transcripts/{conversation_id}/*.jsonl"))
    return loose[0] if loose else None


def resolve_cwd(
    transcript: Path,
    home: Optional[Path] = None,
    external_session_id: Optional[str] = None,
) -> tuple[Optional[str], str]:
    """Recover the session's startup directory. Returns `(cwd, how)`.

    Cursor records the cwd nowhere in the transcript, and its project slug is
    lossy. Two sources, best first:

    1. **The sctx activation lease.** `sctx_facts.get_lease_facts` reads
       `<home>/.shared-context/state/authorized-session-scopes/scope-<digest>.json`,
       which stores `startup_cwd` verbatim. Exact, but only present until
       SessionEnd (or the 30-day reclaim) removes the lease.
    2. **Slug match against the registered Shared Context checkouts.** Every
       registered checkout path is slugified and compared to the transcript's
       project directory name; a unique hit is the cwd. Ambiguity or no hit
       returns None and the caller must be told the cwd.
    """
    import sctx_facts  # local import: avoids a cycle at module import time

    home = home or Path.home()
    if external_session_id:
        lease = sctx_facts.get_lease_facts(home, "cursor", external_session_id)
        cwd = lease.get("lease_startup_cwd")
        if cwd:
            return str(cwd), "sctx activation lease (startup_cwd)"

    slug = transcript.parent.parent.parent.name
    config = home / ".shared-context" / "config.toml"
    if config.is_file():
        try:
            body = config.read_text(encoding="utf-8")
        except OSError:
            body = ""
        candidates = sorted(
            {path for path in re.findall(r'"(/[^"]+)"', body) if slugify_cwd(path) == slug}
        )
        if len(candidates) == 1:
            return candidates[0], "slug match against a registered Shared Context checkout"
        if len(candidates) > 1:
            return None, f"slug {slug!r} matches {len(candidates)} registered checkouts"
    return None, f"slug {slug!r} matches no registered checkout and no lease survives"


def parse_cursor_timestamp(text: str) -> Optional[dt.datetime]:
    """Parse a `<timestamp>` tag body into an aware datetime.

    Real shape: `Tuesday, Sep 8, 2026, 10:27 PM (UTC+8)`. Minute granularity
    (verified against the fixture's own session-start lease at 22:27:34, i.e.
    the tag rounds down), so callers must treat bucket boundaries as fuzzy to
    within a minute.
    """
    match = re.search(
        r"([A-Z][a-z]{2})\s+(\d{1,2}),\s*(\d{4}),\s*(\d{1,2}):(\d{2})\s*([AP]M)"
        r"(?:\s*\(UTC([+-]\d{1,2})(?::(\d{2}))?\))?",
        text,
    )
    if not match:
        return None
    month, day, year, hour, minute, meridiem, tz_hours, tz_minutes = match.groups()
    try:
        stamp = dt.datetime.strptime(
            f"{month} {day} {year} {hour}:{minute} {meridiem}", "%b %d %Y %I:%M %p"
        )
    except ValueError:
        return None
    if tz_hours is None:
        return stamp.replace(tzinfo=dt.timezone.utc)
    offset = dt.timedelta(hours=int(tz_hours), minutes=int(tz_minutes or 0))
    if tz_hours.startswith("-"):
        offset = dt.timedelta(hours=int(tz_hours), minutes=-int(tz_minutes or 0))
    return stamp.replace(tzinfo=dt.timezone(offset))


def split_user_message(text: str) -> tuple[Optional[str], Optional[dt.datetime], str]:
    """Split a Cursor user message into `(query, timestamp, preamble)`.

    `query` is the verbatim `<user_query>` body — what a human actually typed
    and what a replay must resubmit — or None when the message carries no
    query tag at all. `preamble` is everything outside the query tag (the
    timestamp tag, an inlined skill bundle, a `<cursor_commands>` block),
    kept only so the digest can show that it was there.
    """
    stamp = None
    stamp_match = TIMESTAMP_RE.search(text)
    if stamp_match:
        stamp = parse_cursor_timestamp(stamp_match.group(1))
    query_match = USER_QUERY_RE.search(text)
    if not query_match:
        return None, stamp, text
    query = query_match.group(1).strip()
    preamble = (text[: query_match.start()] + text[query_match.end():]).strip()
    return query, stamp, preamble


def is_human_prompt(query: Optional[str]) -> bool:
    if not query:
        return False
    return not query.lstrip().startswith(HOST_QUERY_PREFIXES)


def _blocks(record: dict) -> list:
    message = record.get("message")
    if not isinstance(message, dict):
        return []
    content = message.get("content")
    return content if isinstance(content, list) else []


def _joined_text(blocks: list) -> str:
    return "".join(
        block.get("text", "")
        for block in blocks
        if isinstance(block, dict) and block.get("type") == "text"
    )


ARGUMENTS_UNPARSED_KEY = "__arguments_unparsed__"


def _arguments(raw: Any) -> dict:
    """Normalize `CallDynamicTool.input.arguments` into a dict.

    Usually an object. Sometimes a JSON *string* — and in the fixture the one
    string-valued case is TRUNCATED mid-object (2074 chars ending
    `..."unknowns":[]` with no closing brace), i.e. the host recorded a
    partial tool call. That is a real finding, not a parser problem, so the
    failure is preserved verbatim under `__arguments_unparsed__` instead of
    being silently dropped or hand-repaired; `bundle.compute_facts` counts
    these separately and excludes them from the
    `external_session_id_verbatim` check, which they would otherwise fail for
    the wrong reason.
    """
    if isinstance(raw, dict):
        return raw
    if isinstance(raw, str):
        try:
            parsed = json.loads(raw)
        except json.JSONDecodeError as error:
            return {
                ARGUMENTS_UNPARSED_KEY: True,
                "__arguments_error__": str(error),
                "__arguments_chars__": len(raw),
                "__arguments_text__": raw,
            }
        return parsed if isinstance(parsed, dict) else {"__arguments__": parsed}
    if raw is None:
        return {}
    return {"__arguments__": raw}


def _read_lines(path: Path):
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError:
                continue


def parse_transcript(path: Path, conversation_id: Optional[str] = None) -> Session:
    """Parse a Cursor transcript into a `Session` with no sctx-side data.

    Call `reconstruct_from_sctx()` afterwards to fill in the injections and
    hook events, which this host's transcript cannot supply.
    """
    session = Session(
        meta=SessionMeta(
            host="cursor",
            thread_id=conversation_id or path.stem,
            fidelity_notes=list(FIDELITY_NOTES),
        )
    )
    builder: Optional[Turn] = None

    for record in _read_lines(path):
        if record.get("type") == "turn_ended":
            status = record.get("status")
            if status != "success" and builder is not None:
                error = record.get("error")
                session.other_injections.append(
                    OtherInjection(text_head=f"turn_ended status={status} error={error}"[:80])
                )
            continue

        role = record.get("role")
        blocks = _blocks(record)

        if role == "user":
            text = _joined_text(blocks)
            query, stamp, preamble = split_user_message(text)
            if not is_human_prompt(query):
                head = (query or text).strip().replace("\n", " ")
                session.other_injections.append(
                    OtherInjection(text_head=f"cursor host prompt: {head}"[:80])
                )
                continue
            builder = Turn(
                index=len(session.turns) + 1,
                user_text=query or "",
                started_at=stamp.isoformat() if stamp else None,
            )
            session.turns.append(builder)
            if preamble and "<manually_attached_skills>" in preamble:
                session.other_injections.append(
                    OtherInjection(
                        text_head=f"turn {builder.index} preamble: "
                        f"<manually_attached_skills> ({len(preamble)} chars)"[:80]
                    )
                )
            elif preamble and "<cursor_commands>" in preamble:
                session.other_injections.append(
                    OtherInjection(
                        text_head=f"turn {builder.index} preamble: "
                        f"<cursor_commands> ({len(preamble)} chars)"[:80]
                    )
                )
            continue

        if role != "assistant":
            continue

        for block in blocks:
            if not isinstance(block, dict):
                continue
            kind = block.get("type")
            if kind == "text":
                if builder is not None and block.get("text"):
                    builder.assistant_texts.append(block["text"])
                continue
            if kind != "tool_use":
                continue
            name = block.get("name", "")
            payload = block.get("input")
            payload = payload if isinstance(payload, dict) else {}
            args_text = json.dumps(payload, ensure_ascii=False)
            if builder is None:
                continue
            builder.tool_calls.append(ToolCall(name=name, args_head=args_text[:160]))
            if name == DYNAMIC_CALL_TOOL and is_sctx_namespace(payload.get("namespace")):
                builder.sctx_calls.append(
                    SctxCall(
                        tool=payload.get("toolName") or "",
                        arguments=_arguments(payload.get("arguments")),
                        # Cursor records no tool results at all, so neither the
                        # outcome nor an error code of this call is knowable
                        # from the transcript. `sctx/*.json` in the bundle is
                        # the only place an accept/reject can be checked.
                        status="unknown",
                        result_text=None,
                        error_code=None,
                    )
                )

    if session.turns:
        session.meta.started_at = session.turns[0].started_at
        session.meta.ended_at = session.turns[-1].started_at
    session.meta.cli_version = ""
    session.meta.originator = "cursor-agent"
    return session


