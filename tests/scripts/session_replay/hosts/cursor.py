def _turn_windows(session: Session) -> list:
    """`[(turn, lower_epoch_or_None, upper_epoch_or_None)]`, turn 1's lower
    bound and the last turn's upper bound left open. Returns [] when no turn
    carries a timestamp, which is how pre-timestamp transcripts degrade."""
    starts = []
    for turn in session.turns:
        if turn.started_at:
            starts.append(dt.datetime.fromisoformat(turn.started_at).timestamp())
        else:
            starts.append(None)
    if not any(start is not None for start in starts):
        return []
    windows = []
    for position, turn in enumerate(session.turns):
        lower = None if position == 0 else starts[position]
        upper = starts[position + 1] if position + 1 < len(starts) else None
        windows.append((turn, lower, upper))
    return windows


def _bucket(windows: list, when: Optional[float]) -> Optional[Turn]:
    if when is None or not windows:
        return None
    for turn, lower, upper in windows:
        if (lower is None or when >= lower) and (upper is None or when < upper):
            return turn
    return None


def _task_injection_rows(db_path: Path, external_session_id: str) -> tuple[list, Optional[str]]:
    """All `task_injection` rows for one Cursor session, joined the same way
    `sctx_facts.get_session_facts` joins them (external_session ->
    task_session -> task_id), plus the `xss_...` id for the manifest."""
    if not db_path.exists():
        return [], None
    try:
        with contextlib.closing(
            sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
        ) as connection:
            connection.row_factory = sqlite3.Row
            external = connection.execute(
                "SELECT external_session_id FROM external_session "
                "WHERE agent_kind = 'cursor' AND external_session_key = ?",
                (external_session_id,),
            ).fetchone()
            if external is None:
                return [], None
            xss_id = external["external_session_id"]
            task_ids = [
                row["task_id"]
                for row in connection.execute(
                    "SELECT task_id FROM task_session WHERE external_session_id = ?",
                    (xss_id,),
                )
            ]
            if not task_ids:
                return [], xss_id
            placeholders = ",".join("?" for _ in task_ids)
            rows = [
                dict(row)
                for row in connection.execute(
                    f"SELECT * FROM task_injection WHERE task_id IN ({placeholders}) "  # noqa: S608
                    "ORDER BY injected_at_unix_seconds",
                    tuple(task_ids),
                )
            ]
            return rows, xss_id
    except sqlite3.DatabaseError:
        return [], None


def _group_injections(rows: list) -> list:
    """Group `task_injection` rows into injection EVENTS.

    One `sctx` push writes one row per injected context id, all sharing a
    `(source, injected_at_unix_seconds)` pair — the fixture's 20 rows are 3
    events (3 + 4 + 13). Reporting 20 injections would triple-count the pushes
    and make `injections.count` incomparable with the Codex side.
    """
    grouped: dict = {}
    for row in rows:
        key = (row.get("source"), int(row.get("injected_at_unix_seconds") or 0))
        grouped.setdefault(key, []).append(row)
    events = []
    for (source, when), members in sorted(grouped.items(), key=lambda item: item[0][1]):
        ctx_ids = sorted({row.get("context_id") for row in members if row.get("context_id")})
        revisions = sorted({row.get("intent_revision_id") for row in members if row.get("intent_revision_id")})
        events.append(
            {
                "source": source,
                "injected_at_unix_seconds": when,
                "ctx_ids": ctx_ids,
                "intent_revision_ids": revisions,
                "row_count": len(members),
            }
        )
    return events


def _event_to_injection(event: dict) -> Injection:
    when = dt.datetime.fromtimestamp(
        event["injected_at_unix_seconds"], dt.timezone.utc
    ).isoformat()
    summary = (
        f"[reconstructed from sctx runtime.sqlite/task_injection] "
        f"source={event['source']} injected_at={when} "
        f"context_ids={len(event['ctx_ids'])} "
        f"intent_revision_ids={','.join(event['intent_revision_ids']) or '-'}\n"
        f"{chr(10).join(event['ctx_ids'])}\n"
        "(the injected TEXT is not recorded anywhere on this host: Cursor does "
        "not write hook additionalContext into its transcript, and sctx stores "
        "only the identity of what it injected)"
    )
    return Injection(
        kind=_injection_kind(event["source"]),
        text=summary,
        has_marker=False,
        marker_session_id=None,
        ctx_ids=event["ctx_ids"],
        # Deliberately 0, not a guess: the delivered bytes are unmeasurable
        # here, and a fabricated number would be compared against Codex's real
        # one in facts.json.
        wire_bytes=0,
        est_tokens=0,
        truncated=False,
        reconstructed_from="sctx:task_injection",
    )


def _aggregate_hook_events(events: list) -> list:
    grouped: dict = {}
    for event in events:
        key = (event.get("operation"), event.get("outcome"), event.get("reason"))
        bucket = grouped.setdefault(key, [])
        bucket.append(event.get("occurred_at_unix_ms"))
    aggregated = []
    for (operation, outcome, reason), stamps in grouped.items():
        clean = sorted(stamp for stamp in stamps if stamp is not None)
        aggregated.append(
            HookEvent(
                operation=operation or "",
                outcome=outcome or "",
                reason=reason,
                count=len(stamps),
                first_at_unix_ms=clean[0] if clean else None,
                last_at_unix_ms=clean[-1] if clean else None,
            )
        )
    return sorted(aggregated, key=lambda item: (item.first_at_unix_ms or 0, item.operation))


def reconstruct_from_sctx(
    session: Session,
    home: Path,
    external_session_id: Optional[str] = None,
) -> dict:
    """Fill in `Turn.injections` and `Turn.hook_events` from sctx's own state.

    Mutates `session` and returns (and stores on `session.reconstruction`) the
    provenance record: which files were read, what the per-turn windows were,
    and which rows could not be attributed to a turn.
    """
    session_id = external_session_id or session.meta.thread_id
    db_path = home / ".shared-context" / "state" / "runtime.sqlite"
    logs_root = home / ".shared-context-logs"

    rows, xss_id = _task_injection_rows(db_path, session_id)
    events = _group_injections(rows)

    digest = sctx_logs.telemetry_session_digest("cursor", session_id)
    diagnostics_path = logs_root / "state" / "hook-diagnostics.json"
    hook_events: list = []
    # `hook-diagnostics.json` is written by the sctx LOG COLLECTOR service, not
    # by the hooks themselves. A replay HOME starts with an empty
    # `.shared-context-logs/` and no collector running in it, so the file is
    # simply absent there -- which must not be reported as "no hooks ran". The
    # replay's own hook traffic is captured by `replay_cursor.py` into
    # `host/hook-input.jsonl` / `host/hook-output.jsonl` and summarised in
    # `manifest.isolation.hooks` instead.
    if not diagnostics_path.is_file():
        hook_source = f"unavailable: {diagnostics_path} does not exist"
    elif not digest:
        hook_source = "unavailable: no telemetry digest for this session id"
    else:
        hook_source = str(diagnostics_path)
        try:
            with open(diagnostics_path, "r", encoding="utf-8") as handle:
                diagnostics = json.load(handle)
            hook_events = [
                event
                for event in (diagnostics.get("recent_events") or [])
                if event.get("session_digest") == digest
            ]
        except (OSError, json.JSONDecodeError) as error:
            hook_source = f"unreadable: {diagnostics_path} ({error})"

    windows = _turn_windows(session)
    unwindowed_injections: list = []
    unwindowed_hook_events: list = []

    for event in events:
        turn = _bucket(windows, float(event["injected_at_unix_seconds"]))
        if turn is None:
            unwindowed_injections.append(event)
        else:
            turn.injections.append(_event_to_injection(event))

    per_turn_hooks: dict = {}
    for event in hook_events:
        stamp = event.get("occurred_at_unix_ms")
        turn = _bucket(windows, stamp / 1000.0 if stamp is not None else None)
        if turn is None:
            unwindowed_hook_events.append(event)
        else:
            per_turn_hooks.setdefault(turn.index, []).append(event)
    for turn in session.turns:
        turn.hook_events = _aggregate_hook_events(per_turn_hooks.get(turn.index, []))

    record = {
        "source": "sctx",
        "reason": (
            "Cursor transcripts record neither hook injections nor tool "
            "results; injections and hook events below are rebuilt from "
            "sctx's own state and are flagged reconstructed_from"
        ),
        "runtime_sqlite": str(db_path),
        "external_session_id": xss_id,
        "hook_diagnostics": str(diagnostics_path),
        "hook_diagnostics_available": not hook_source.startswith(("unavailable", "unreadable")),
        "hook_diagnostics_source": hook_source,
        "hook_diagnostics_session_digest": digest,
        "task_injection_rows": len(rows),
        "task_injection_events": len(events),
        "hook_diagnostics_events": len(hook_events),
        "turn_windows": [
            {
                "turn": turn.index,
                "started_at": turn.started_at,
                "lower_unix_seconds": lower,
                "upper_unix_seconds": upper,
            }
            for turn, lower, upper in windows
        ],
        "windowing": (
            "per-turn (<timestamp> tags present; minute granularity, so rows "
            "within ~60s of a boundary may fall on either side)"
            if windows
            else "session-level only (no <timestamp> tag in any user message)"
        ),
        "unwindowed": {
            "injection_events": unwindowed_injections,
            "injection_ctx_ids": sorted(
                {ctx for event in unwindowed_injections for ctx in event["ctx_ids"]}
            ),
            "hook_event_count": len(unwindowed_hook_events),
            "hook_events": _serialize_hook_events(
                _aggregate_hook_events(unwindowed_hook_events)
            ),
        },
    }
    session.reconstruction = record
    return record


def _serialize_hook_events(events: list) -> list:
    return [
        {
            "operation": event.operation,
            "outcome": event.outcome,
            "reason": event.reason,
            "count": event.count,
            "first_at_unix_ms": event.first_at_unix_ms,
            "last_at_unix_ms": event.last_at_unix_ms,
        }
        for event in events
    ]


def load_session(
    conversation_id: str,
    home: Optional[Path] = None,
    cursor_home: Optional[Path] = None,
    transcript: Optional[Path] = None,
    reconstruct: bool = True,
) -> tuple[Session, Optional[Path]]:
    """Resolve, parse and (by default) reconstruct one Cursor session."""
    home = home or Path.home()
    path = transcript or resolve_transcript(conversation_id, cursor_home=cursor_home)
    if path is None:
        return Session(meta=SessionMeta(host="cursor", thread_id=conversation_id)), None
    session = parse_transcript(path, conversation_id=conversation_id)
    cwd, how = resolve_cwd(path, home=home, external_session_id=conversation_id)
    if cwd:
        session.meta.cwd = cwd
        session.meta.fidelity_notes.append(f"cwd recovered via {how}")
    else:
        session.meta.fidelity_notes.append(f"cwd unknown: {how}")
    if reconstruct:
        reconstruct_from_sctx(session, home, external_session_id=conversation_id)
    return session, path
